from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from statistics import mean, stdev
from typing import Any


DEFAULT_FORMATS = ("cass", "json", "meds", "xml")
DEFAULT_METRICS = (
    ("mean_prediction_std", "Prob. std."),
    ("mean_max_probability_gap", "Risk span"),
    ("label_flip_rate", "Flip rate"),
)


def _compact(value: float) -> str:
    text = f"{value:.3f}"
    if text.startswith("0"):
        text = text[1:]
    if text.startswith("-0"):
        text = "-" + text[2:]
    return text


def _pm(values: list[float]) -> str:
    if len(values) == 1:
        return _compact(values[0])
    return f"{_compact(mean(values))}$\\pm${_compact(stdev(values))}"


def _read_metric(path: Path, key: str) -> float:
    payload = json.loads(path.read_text(encoding="utf-8"))
    section: Any = payload
    for part in key.split("."):
        section = section[part]
    return float(section)


def collect(root: Path, formats: tuple[str, ...], center: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for fmt in formats:
        paths = sorted((root / "permutation").glob(f"*/{fmt}_seed*/{center}/metrics.json"))
        if not paths:
            paths = sorted(root.glob(f"**/{fmt}_seed*/{center}/metrics.json"))
        if not paths:
            raise FileNotFoundError(f"No metrics found for format={fmt!r}, center={center!r} under {root}")
        row: dict[str, Any] = {"format": fmt, "center": center, "n_files": len(paths)}
        for metric, _label in DEFAULT_METRICS:
            values = [_read_metric(path, f"permutation.{metric}") for path in paths]
            row[f"{metric}_mean"] = mean(values)
            row[f"{metric}_std"] = stdev(values) if len(values) > 1 else 0.0
        if all("text" in json.loads(path.read_text(encoding="utf-8")) for path in paths):
            for metric in ("mean_unique_hashes", "exact_match_rate"):
                values = [_read_metric(path, f"text.{metric}") for path in paths]
                row[f"{metric}_mean"] = mean(values)
                row[f"{metric}_std"] = stdev(values) if len(values) > 1 else 0.0
        rows.append(row)
    return rows


def write_csv(rows: list[dict[str, Any]], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    fields = sorted({key for row in rows for key in row})
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(rows: list[dict[str, Any]], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "| Representation | Files | Prob. std. | Risk span | Flip rate |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        values = [str(row["format"]).upper(), str(row["n_files"])]
        for metric, _label in DEFAULT_METRICS:
            values.append(
                f"{_compact(float(row[f'{metric}_mean']))}+/-{_compact(float(row[f'{metric}_std']))}"
            )
        lines.append("| " + " | ".join(values) + " |")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_tex(rows: list[dict[str, Any]], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        r"\begin{table}[t]",
        r"\caption{Representation sensitivity under legal surface perturbations. Values are aggregated from permutation audit metrics generated by the audit scripts. Lower values indicate more stable predictions.}",
        r"\label{tab:representation_stability}",
        r"\centering",
        r"\small",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Representation & Prob. std. & Risk span & Flip rate \\",
        r"\midrule",
    ]
    for row in rows:
        cells = [str(row["format"]).upper()]
        for metric, _label in DEFAULT_METRICS:
            mean_value = float(row[f"{metric}_mean"])
            std_value = float(row[f"{metric}_std"])
            cells.append(f"{_compact(mean_value)}$\\pm${_compact(std_value)}")
        lines.append(" & ".join(cells) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Build Table 2 from representation permutation audit metrics.")
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--center", default="mimic")
    parser.add_argument("--formats", nargs="+", default=list(DEFAULT_FORMATS))
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--markdown", type=Path, required=True)
    parser.add_argument("--tex", type=Path, required=True)
    args = parser.parse_args()

    rows = collect(args.root, tuple(args.formats), args.center)
    write_csv(rows, args.csv)
    write_markdown(rows, args.markdown)
    write_tex(rows, args.tex)
    print(json.dumps(rows, indent=2))


if __name__ == "__main__":
    main()
